JOIN PA_ACREEDORES     a  ON a.ACREEDOR_ID = f.ACREEDOR_ID
JOIN PA_PAISES         p  ON p.PAIS_ID     = a.PAIS_ID
LEFT JOIN PA_DETALLES_FACTURA df 
       ON df.FACTURA_ID = f.FACTURA_ID
WHERE df.FECHA_ELIMINACION IS NULL;
