-- ============================================
-- QUERIES DE PRUEBA
-- ============================================

-- Ver propuestas creadas
SELECT 
    p.PROPUESTA_DE_PAGO_ID,
    p.ESTADO,
    p.FECHA_HORA_CREACION,
    eb.NOMBRE AS BANCO,
    pa.NOMBRE AS PAIS,
    COUNT(dp.DETALLE_PROPUESTA_ID) AS TOTAL_PAGOS
FROM PA_PROPUESTAS_DE_PAGO p
JOIN PA_ENTIDADES_BANCARIAS eb ON eb.ENTIDAD_BANCARIA_ID = p.ENTIDAD_BANCARIA_ID
JOIN PA_PAISES pa ON pa.PAIS_ID = eb.PAIS_ID
LEFT JOIN PA_DETALLES_PROPUESTA dp ON dp.PROPUESTA_DE_PAGO_ID = p.PROPUESTA_DE_PAGO_ID
    AND dp.FECHA_ELIMINACION IS NULL
GROUP BY p.PROPUESTA_DE_PAGO_ID, p.ESTADO, p.FECHA_HORA_CREACION, eb.NOMBRE, pa.NOMBRE
ORDER BY p.PROPUESTA_DE_PAGO_ID;

